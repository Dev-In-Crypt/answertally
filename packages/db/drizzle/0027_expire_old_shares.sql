-- Ссылки на отчёты, выданные до появления срока, были вечными. Политика и
-- DPA обещают, что у ссылки есть срок: выдаём им те же 90 дней от выкатки.
-- Данные не удаляются; откат — вернуть NULL этим строкам.
UPDATE "report_shares" SET "expires_at" = now() + interval '90 days' WHERE "expires_at" IS NULL;
