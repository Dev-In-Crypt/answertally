import { PLATFORM_IDS, type Platform } from "./types";

/**
 * Во что обходится один ответ каждого ассистента.
 *
 * Оценка для планирования, а не счёт. Настоящая стоимость каждого ответа
 * пишется в `responses.cost_usd` самим адаптером по прайсу провайдера и по
 * фактически потраченным токенам; когда живых прогонов накопится достаточно,
 * эту таблицу надо пересчитать по ним.
 *
 * До сих пор в коде была одна цифра на всех — цена ответа ChatGPT. Ассистенты
 * различаются почти впятеро: самый дешёвый ответ стоит $0.0116, самый дорогой
 * $0.0560. Одна цифра занижала расход на запускной тройке примерно на пятую
 * часть, а на дорогом наборе — вдвое с лишним. Планировать по такой оценке
 * значит планировать не то.
 *
 * Живая проверка 2026-09-29 показала, что арифметика по прайсу врала, и
 * сильно: Perplexity оказался в 8 раз дешевле оценки, Claude в 1,5 раза
 * дороже, Grok — в 4,8 раза дороже. Ошибка была не в ценах на токены, они
 * были верны, а в профиле ответа. Расчёт брал ~4 000 входных токенов, но
 * ответ с поиском втягивает содержимое найденных страниц: у OpenAI это
 * ~8 000 токенов на каждый поиск сверх платы за сам вызов, у Grok счёт
 * дошёл до десятков тысяч. Входных токенов оказывается не четыре тысячи, а
 * двадцать-шестьдесят, и умножаются они на цену входа.
 *
 * Отсюда правило: цену ответа с поиском нельзя вывести из прайса, её можно
 * только снять. Ниже — снятые значения, по одному вызову на платформу.
 * Один вызов — не распределение: число поисков гуляет от вопроса к вопросу,
 * а с ним и цена. Это лучше прежней арифметики, но всё ещё оценка.
 *
 * ChatGPT измерен дважды: $0.0242 на gpt-5.6-luna и $0.0116 на gpt-6-luna,
 * которая стала умолчанием. Стоит второе — первое описывает модель, которой
 * продукт больше не пользуется.
 *
 * Лимитов тарифов и цен эта цифра не задаёт: они отдельные числа в
 * `PLAN_LIMITS`. Отсюда берётся только наша оценка расхода, и завышать её
 * вдвое — не осторожность, а неверные данные: они прячут то, что дорого
 * обходится не ChatGPT, а Grok.
 *
 * Подробности расчёта — docs/cost-model.md §1.
 */

export interface AnswerPrice {
  /** Оценка стоимости одного ответа в долларах. */
  usd: number;
  /**
   * `measured` — снято на живом вызове; `listed` — посчитано по прайсу
   * провайдера. Разница существенна: второе не проверялось счётом.
   */
  basis: "measured" | "listed";
  /** Когда цифра получена, ISO-дата. */
  on: string;
}

export const ANSWER_PRICES: Record<Platform, AnswerPrice> = {
  perplexity: { usd: 0.0014, basis: "measured", on: "2026-09-29" },
  chatgpt: { usd: 0.0116, basis: "measured", on: "2026-10-02" },
  claude: { usd: 0.0817, basis: "measured", on: "2026-09-29" },
  // Самый дорогой из всех. С 07.10.2026 вне набора по умолчанию и весит
  // 5 проверок (CHECK_WEIGHTS).
  grok: { usd: 0.1058, basis: "measured", on: "2026-09-29" },
  // Не измеряется: условия Google на grounded-поиск. Строка нужна типу.
  gemini: { usd: 0.055, basis: "listed", on: "2026-09-23" },
  // DataForSEO, живые вызовы 07.10.2026: AI Mode $0.004, выдача с блоком
  // AI Overview $0.002.
  "ai-mode": { usd: 0.004, basis: "measured", on: "2026-10-07" },
  "ai-overviews": { usd: 0.002, basis: "measured", on: "2026-10-07" },
};

/**
 * Цена ответа неизвестного ассистента.
 *
 * Берётся самая дорогая из известных, а не средняя: ошибаться в планировании
 * расхода лучше в сторону «дороже, чем окажется». Случай возможен только при
 * добавлении платформы, у которой забыли завести цену, — и тогда оценка
 * должна беспокоить, а не успокаивать.
 */
const DEAREST_USD = Math.max(...PLATFORM_IDS.map((id) => ANSWER_PRICES[id].usd));

/** Оценка стоимости одного ответа этого ассистента. */
export function answerPriceUsd(platform: string): number {
  return ANSWER_PRICES[platform as Platform]?.usd ?? DEAREST_USD;
}

/**
 * Во что обойдётся один прогон по набору: сумма цен, а не цена, умноженная
 * на количество. Именно в этом и была ошибка прежней оценки.
 */
export function answersCostUsd(assistants: readonly string[], answersEach: number): number {
  const perRound = assistants.reduce((sum, id) => sum + answerPriceUsd(id), 0);
  // Шесть знаков — та же точность, что у колонки cost_usd.
  return Math.round(perRound * answersEach * 1_000_000) / 1_000_000;
}

/**
 * Сколько проверок из месячного лимита списывает один ответ ассистента.
 *
 * Решение фаундера 07.10.2026: Grok 5, Claude 4, ChatGPT и Perplexity по 1.
 * Без весов лимит в проверках не держал деньги: ответ Grok в 75 раз дороже
 * ответа Perplexity, и агентство, гоняющее только Grok и Claude, уводило
 * Growth и Scale в минус. С весами самый дорогой расклад на любом тарифе —
 * около четверти цены.
 *
 * Неизвестная платформа считается по самому тяжёлому весу: ошибка в сторону
 * осторожности, как и с ценой ответа.
 */
export const CHECK_WEIGHTS: Record<Platform, number> = {
  chatgpt: 1,
  perplexity: 1,
  claude: 4,
  grok: 5,
  gemini: 4,
  "ai-overviews": 1,
  "ai-mode": 1,
};

const HEAVIEST_WEIGHT = Math.max(...PLATFORM_IDS.map((id) => CHECK_WEIGHTS[id]));

export function checkWeight(platform: string): number {
  return CHECK_WEIGHTS[platform as Platform] ?? HEAVIEST_WEIGHT;
}

/** Проверок за один круг «каждый ассистент ответил один раз». */
export function checkUnits(platforms: readonly string[]): number {
  return platforms.reduce((sum, platform) => sum + checkWeight(platform), 0);
}
