import { PLAN_LIMITS } from "./period";

/**
 * Партнёрские условия агентства.
 *
 * Две вещи, и они платят за разное. Оптовая цена — за объём: клиентские
 * аккаунты, которые агентство приводит само и ведёт дальше. Комиссия — за
 * приведённое агентство, то есть за знакомство. Смешивать их в одну ставку
 * значило бы платить одинаково тому, кто построил практику, и тому, кто один
 * раз переслал письмо.
 *
 * Почему числа живут здесь, а не в тексте страницы: они одновременно
 * обещание покупателю и правило биллинга. Одно и то же число, набранное в
 * двух местах, однажды разойдётся, и разойдётся оно в худшую сторону — на
 * странице останется старая цена, по которой агентство уже согласилось.
 *
 * Обоснование выбора — docs/competitor-partner-programmes.md §4, вариант C
 * вместе с B. В отрасли об «особых условиях» говорят все, а число не
 * печатает никто.
 */

/** Сколько аккаунтов покрывает старший тариф; оптовая цена — с аккаунта сверх этого числа. */
export const VOLUME_THRESHOLD = PLAN_LIMITS.scale.clientLimit;

/** Скидка на аккаунты сверх порога. */
export const VOLUME_DISCOUNT = 0.2;

/**
 * Цена аккаунта на старшем тарифе — база, от которой считается скидка.
 *
 * Считается, а не вписывается: тариф и его вместимость уже определены в
 * `PLAN_LIMITS`, и второе определение той же цены разъехалось бы с первым
 * при любом пересмотре.
 */
export const LIST_ACCOUNT_PRICE_USD = Math.round(
  PLAN_LIMITS.scale.priceUsd / PLAN_LIMITS.scale.clientLimit,
);

/** Цена каждого аккаунта сверх порога. */
export const VOLUME_ACCOUNT_PRICE_USD = Math.round(
  LIST_ACCOUNT_PRICE_USD * (1 - VOLUME_DISCOUNT),
);

/**
 * Комиссия за приведённое агентство и срок, на который она платится.
 *
 * Ограничение по сроку — принятая в отрасли форма, а не скупость: бессрочная
 * доля с каждого платежа переживает любую причину, по которой она была
 * назначена.
 */
export const REFERRAL_RATE = 0.2;
export const REFERRAL_MONTHS = 12;

/**
 * Во что обходится агентству месяц при таком числе клиентских аккаунтов.
 *
 * Скидка действует только на аккаунты сверх порога. Распространить её на
 * все сразу значило бы завести обрыв: двадцать шестой клиент уменьшал бы
 * наш доход по сравнению с двадцатью пятью, и добавление клиента стало бы
 * для нас убытком. Здесь добавленный клиент всегда прибавляет.
 */
export function monthlyTotalUsd(accounts: number): number {
  if (accounts <= VOLUME_THRESHOLD) {
    return PLAN_LIMITS.scale.priceUsd;
  }

  return (
    PLAN_LIMITS.scale.priceUsd + (accounts - VOLUME_THRESHOLD) * VOLUME_ACCOUNT_PRICE_USD
  );
}

/** Средняя цена аккаунта при таком объёме — то, что агентство сравнивает. */
export function effectiveAccountPriceUsd(accounts: number): number {
  if (accounts <= 0) return 0;
  return Math.round((monthlyTotalUsd(accounts) / accounts) * 100) / 100;
}
