import { parseEmailMode } from "@repo/core";

/**
 * Требовать ли подтверждение адреса при регистрации.
 *
 * Привязано к тому, умеет ли продукт слать письма, а не к отдельному
 * выключателю. Причина простая: в режиме лога ссылка подтверждения уходит
 * в журнал сервера, и требовать её значило бы закрыть регистрацию наглухо
 * любому, кто поднял продукт без ключа Resend. Остальное в продукте
 * деградирует без ключей безопасно, и это должно вести себя так же.
 *
 * Заодно отсюда следует, что сквозные тесты остаются рабочими без
 * специальных флагов: они идут на почте в режиме лога.
 *
 * Лежит отдельно от настройки входа намеренно: та поднимает соединение с
 * базой при импорте, а правило — чистое, и проверять его базой не нужно.
 */
export function requiresEmailVerification(
  env: Record<string, string | undefined> = process.env,
): boolean {
  return parseEmailMode(env["EMAIL_MODE"]?.trim()) === "live";
}
